-- =====================================================================
--  SELECTS PRINCIPALS
-- =====================================================================

-- Ranking de jugadors per partides guanyades
SELECT playerName, colour, games_played, games_won
FROM ENTITY
WHERE entityType = 'PLAYER'
ORDER BY games_won DESC, games_played DESC;

-- Jugadors d'una partida amb posició actual
SELECT e.entityID, e.playerName, e.colour, s.squareID, s.type, g.gameState
FROM ENTITY e
JOIN GAME g   ON e.gameID   = g.gameID
JOIN SQUARE s ON e.squareID = s.squareID
WHERE g.gameID = 1
ORDER BY e.playerName;

-- Inventari complet d'un jugador
SELECT e.playerName, o.type, o.diceType, o.quantity
FROM ENTITY e
JOIN INVENTORY i ON e.inventoryID = i.inventoryID
JOIN OBJECT o    ON o.inventoryID = i.inventoryID
WHERE e.entityID = 1;

-- Caselles especials del tauler
SELECT squareID, type, destination, eventID
FROM SQUARE
WHERE boardID = 1
  AND type != 'NORMAL'
ORDER BY squareID;

-- Partides en curs
SELECT gameID, gameState, gameDate, boardID
FROM GAME
WHERE gameState = 'IN_PROGRESS'
ORDER BY gameDate DESC;

-- Llistat de partides desades
SELECT GAME_ID, SAVE_DATE
FROM SAVED_GAMES
ORDER BY SAVE_DATE DESC;

-- Esdeveniments disponibles
SELECT eventID, type
FROM EVENT
ORDER BY eventID;
