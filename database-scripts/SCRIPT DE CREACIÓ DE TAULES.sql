CREATE TABLE BOARD (
    boardID     NUMBER(5)       PRIMARY KEY
);

CREATE TABLE EVENT (
    eventID     NUMBER(5)       PRIMARY KEY,
    type        VARCHAR2(20)    NOT NULL,
    CONSTRAINT ck_event_type CHECK (type IN (
        'GET_FISH', 'GET_SNOWBALLS', 'GET_FAST_DICE', 'GET_SLOW_DICE',
        'LOSE_TURN', 'LOSE_ITEM', 'SNOWMOBILE'))
);

CREATE TABLE GAME (
    gameID      NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gameState   VARCHAR2(20)    NOT NULL,
    gameDate    DATE            DEFAULT SYSDATE,
    boardID     NUMBER(5),
    CONSTRAINT fk_game_board FOREIGN KEY (boardID) REFERENCES BOARD(boardID)
);

CREATE TABLE SQUARE (
    squareID    NUMBER(3)       PRIMARY KEY,
    type        VARCHAR2(15)    NOT NULL,
    destination NUMBER(3),
    eventID     NUMBER(5),
    boardID     NUMBER(5),
    CONSTRAINT fk_square_destination FOREIGN KEY (destination) REFERENCES SQUARE(squareID),
    CONSTRAINT fk_square_event       FOREIGN KEY (eventID)     REFERENCES EVENT(eventID),
    CONSTRAINT fk_square_board       FOREIGN KEY (boardID)     REFERENCES BOARD(boardID),
    CONSTRAINT ck_square_type CHECK (type IN (
        'NORMAL', 'BEAR', 'ICE_HOLE', 'SLED', 'EVENT',
        'BROKEN_FLOOR', 'START', 'END'))
);

CREATE TABLE INVENTORY (
    inventoryID NUMBER(10)      PRIMARY KEY,
    entityID    NUMBER(10)
);

CREATE TABLE ENTITY (
    entityID        NUMBER(10)      PRIMARY KEY,
    squareID        NUMBER(3),
    entityType      VARCHAR2(10)    NOT NULL,
    gameID          NUMBER(10),
    inventoryID     NUMBER(10),
    playerName      VARCHAR2(30),
    -- AES-128 + Base64 → reservem espai suficient
    playerPassword  VARCHAR2(200),
    colour          VARCHAR2(6),
    games_played    NUMBER(10)      DEFAULT 0,
    games_won       NUMBER(10)      DEFAULT 0,
    CONSTRAINT fk_entity_square    FOREIGN KEY (squareID)    REFERENCES SQUARE(squareID),
    CONSTRAINT fk_entity_game      FOREIGN KEY (gameID)      REFERENCES GAME(gameID),
    CONSTRAINT fk_entity_inventory FOREIGN KEY (inventoryID) REFERENCES INVENTORY(inventoryID),
    CONSTRAINT ck_entity_type      CHECK (entityType IN ('PLAYER', 'SEAL')),
    CONSTRAINT ck_player_name      CHECK ((entityType = 'PLAYER' AND playerName IS NOT NULL)
                                        OR (entityType = 'SEAL'   AND playerName IS NULL)),
    CONSTRAINT uq_entity_name      UNIQUE (playerName)
);

ALTER TABLE INVENTORY ADD CONSTRAINT fk_inventory_entity
    FOREIGN KEY (entityID) REFERENCES ENTITY(entityID);

CREATE TABLE OBJECT (
    objectID    NUMBER(10)      PRIMARY KEY,
    inventoryID NUMBER(10),
    type        VARCHAR2(10)    NOT NULL,
    diceType    VARCHAR2(8),
    quantity    NUMBER(2),
    CONSTRAINT fk_object_inventory FOREIGN KEY (inventoryID) REFERENCES INVENTORY(inventoryID),
    CONSTRAINT ck_object_type      CHECK (type IN ('DICE', 'FISH', 'SNOWBALL')),
    CONSTRAINT ck_object_diceType  CHECK ((type = 'DICE'  AND diceType IN ('FAST', 'SLOW'))
                                        OR (type != 'DICE' AND diceType IS NULL)),
    CONSTRAINT ck_object_quantity  CHECK ((type = 'FISH'     AND quantity BETWEEN 0 AND 2)
                                        OR (type = 'SNOWBALL' AND quantity BETWEEN 0 AND 6)
                                        OR (type = 'DICE'     AND quantity BETWEEN 0 AND 3))
);

-- ---------------------------------------------------------------------
--  SAVED_GAMES — payload YAML xifrat amb AES-128 (CryptoUtil)
-- ---------------------------------------------------------------------
CREATE TABLE SAVED_GAMES (
    GAME_ID     VARCHAR2(50)    PRIMARY KEY,
    GAME_DATA   CLOB            NOT NULL,
    SAVE_DATE   DATE            DEFAULT SYSDATE
);

